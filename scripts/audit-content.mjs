// Run: npm run audit — READ-ONLY inventory of all historical content. Writes docs/CONTENT_AUDIT.md. Never modifies content.
import { readFileSync, writeFileSync, readdirSync, mkdtempSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { build } from 'esbuild'

const out = join(mkdtempSync(join(tmpdir(), 'sira-audit-')), 'm.mjs')
const bioFiles = readdirSync('src/bio').filter((f) => f.endsWith('.ts') && !['index.ts', 'types.ts'].includes(f))
await build({ stdin: { contents: `export { SAMPLE } from './src/data.ts'; export * from './src/chrono/def.ts'; ${bioFiles.map((f, i) => `export * as b${i} from './src/bio/${f}'`).join(';')}`, resolveDir: process.cwd() }, bundle: true, format: 'esm', outfile: out, loader: { '.json': 'json' }, logLevel: 'silent' })
const m = await import(out)
const { SAMPLE, EVENTS, GROUPS } = m
const BIOS = bioFiles.map((_, i) => Object.values(m[`b${i}`])[0])
const J = (p) => JSON.parse(readFileSync(p, 'utf8'))
const LANGS = ['ar', 'fr', 'en', 'es']
const byId = new Map(SAMPLE.map((e) => [e.id, e]))
const L = []
const h = (n, t) => L.push('', `${'#'.repeat(n)} ${t}`, '')
const table = (head, rows) => { L.push(`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`); rows.forEach((r) => L.push(`| ${r.join(' | ')} |`)); L.push('') }
const tally = (arr, f) => arr.reduce((a, x) => ((a[f(x)] = (a[f(x)] ?? 0) + 1), a), {})
const fmt = (o) => Object.entries(o).map(([k, v]) => `${k} ${v}`).join(', ') || '—'

L.push('# Content audit', '', '_Generated by `npm run audit` (read-only). No historical claim was modified. Regenerate after any content change._')

// ---------- 1. inventory ----------
h(2, '1. Inventory by content type')
const kinds = tally(SAMPLE, (e) => e.kind)
const claims = BIOS.flatMap((b) => b.sections.flatMap((s) => s.claims.map((c) => ({ ...c, bio: b.id }))))
const srcAll = [...SAMPLE.flatMap((e) => e.sources.map(([t, r]) => [t, r, `entity:${e.id}`])), ...BIOS.flatMap((b) => Object.values(b.sources).map(([t, r]) => [t, r, `bio:${b.id}`]))]
const distinct = new Set(srcAll.map(([t, r]) => t + '§' + r))
const edges = new Set(SAMPLE.flatMap((e) => e.rel.map((r) => [e.id, r].sort().join('~'))))
table(['Content type', 'Count', 'Notes'], [
  ['Entities (all)', SAMPLE.length, fmt(kinds)],
  ['Timeline events', EVENTS.length, `${EVENTS.filter((x) => byId.get(x.id)?.kind === 'event').length} are entities of kind "event"`],
  ['Historical stages', GROUPS.length, 'g1…g17, titles in 4 languages'],
  ['Biographies', BIOS.length, BIOS.map((b) => `${b.id} (${b.sections.length} sections, ${b.sections.flatMap((s) => s.claims).length} claims, ${b.facts.length} facts, ${b.journey.length} milestones)`).join('; ')],
  ['Biography claims', claims.length, BIOS.map((b) => `${b.id} ${claims.filter((c) => c.bio === b.id).length}`).join(', ')],
  ['Source references (entity + biography)', srcAll.length, `${distinct.size} distinct (title + locator)`],
  ['Relationships (undirected entity↔entity)', edges.size, `${SAMPLE.reduce((a, e) => a + e.rel.length, 0)} directed links in data`],
  ['Languages', 4, 'ar (original), fr, en, es'],
])

// ---------- 2. historical review status ----------
h(2, '2. Historical review status (current)')
L.push('Today the only recorded review state is the legacy per-language `verification` field. Nothing has been reviewed.', '')
const rows = []
for (const l of LANGS) {
  const c = J(`src/locales/content/${l}.json`)
  rows.push([`entities (${l})`, SAMPLE.length, fmt(tally(Object.values(c.entities), (e) => e.verification?.status ?? 'MISSING'))])
}
for (const b of BIOS) for (const l of LANGS) rows.push([`biography ${b.id} (${l})`, 1, J(`src/bio/${b.id}/${l}.json`).verification?.status ?? 'MISSING'])
for (const l of LANGS) rows.push([`timeline stages (${l})`, GROUPS.length, J(`src/chrono/${l}.json`).verification?.status ?? 'MISSING'])
table(['Record set', 'Records', 'Status'], rows)
L.push('The legacy field mixes two concepts (review status and classification, e.g. `DISPUTED`). The editorial model separates them — see `docs/EDITORIAL_MODEL.md`.', '')

// ---------- 3. classification ----------
h(2, '3. Historical account classification')
const evCert = tally(EVENTS, (x) => x.certainty)
const claimCert = tally(claims, (c) => c.certainty)
const factCert = tally(BIOS.flatMap((b) => b.facts), (c) => c.certainty)
table(['Record set', 'Total', 'established / disputed / uncertain'], [
  ['Timeline events', EVENTS.length, `${evCert.established ?? 0} / ${evCert.disputed ?? 0} / ${evCert.uncertain ?? 0}`],
  ['Biography claims', claims.length, `${claimCert.established ?? 0} / ${claimCert.disputed ?? 0} / ${claimCert.uncertain ?? 0}`],
  ['Biography facts', BIOS.flatMap((b) => b.facts).length, `${factCert.established ?? 0} / ${factCert.disputed ?? 0} / ${factCert.uncertain ?? 0}`],
])
const noClass = SAMPLE.filter((e) => e.kind !== 'event')
L.push(`**Gap:** ${noClass.length} entities (people, places, groups) have **no classification at all** (only free-text \`disputed\` notes on ${noClass.filter((e) => e.disputed).length} of them): ${noClass.map((e) => e.id).join(', ')}.`, '')
const mismatch = []
for (const b of BIOS) for (const j of b.journey) { const t = j.entity === j.id ? EVENTS.find((x) => x.id === j.id) : null; if (t && t.certainty !== j.certainty) mismatch.push(`${b.id} milestone "${j.id}" is ${j.certainty} but the timeline says ${t.certainty}`) }
L.push(mismatch.length ? `**Classification conflicts between records:**\n${mismatch.map((x) => `- ${x}`).join('\n')}` : '**Classification conflicts between biography milestones and the timeline:** none found.', '')

// ---------- 4. translation status ----------
h(2, '4. Translation status per language')
const tr = []
for (const l of ['fr', 'en', 'es']) {
  const c = J(`src/locales/content/${l}.json`)
  const bs = BIOS.map((b) => J(`src/bio/${b.id}/${l}.json`).translation?.status)
  tr.push([l, fmt(tally(Object.values(c.entities), (e) => e.translation?.status ?? 'MISSING')), fmt(tally(bs, (s) => s ?? 'MISSING')), J(`src/chrono/${l}.json`).translation?.status ?? 'MISSING'])
}
table(['Language', `Entities (${SAMPLE.length})`, `Biographies (${BIOS.length})`, 'Timeline stage titles'], tr)
L.push('Arabic is the original and has no translation status. Every fr/en/es record is an unreviewed draft; none is approved.', '')

// ---------- 5. sources ----------
h(2, '5. Source references')
const isQuran = (t) => t === 'القرآن الكريم'
const verseLevel = (t, r) => isQuran(t) && /\d/.test(r)
const vague = /مواضع متفرقة|الجزء الأول والثاني|^المقدمة$|^مقدمة الطبقات$|^كتاب المناقب$|^كتاب بدء الخلق$/
const pageNo = /(ص|صفحة)\s*\d+|p\.\s*\d+/i, hadithNo = /(حديث|رقم)\s*\d+/, vol = /(الجزء|المجلد|ج)\s*\d+/
const withPage = [...distinct].filter((k) => { const [, r] = k.split('§'); return pageNo.test(r) || hadithNo.test(r) || vol.test(r) }).length
const works = tally([...distinct].map((k) => k.split('§')), ([t]) => t)
table(['Metric', 'Value'], [
  ['Distinct references', distinct.size],
  ['…with a page, volume or hadith number', `${withPage} (none can be treated as complete)`],
  ['…Qur\'ān references with a verse number', [...distinct].filter((k) => verseLevel(...k.split('§'))).length],
  ['…Qur\'ān references at sūra level only', [...distinct].filter((k) => { const [t, r] = k.split('§'); return isQuran(t) && !/\d/.test(r) }).length],
  ['Entities with no source', SAMPLE.filter((e) => !e.sources.length).map((e) => e.id).join(', ') || 'none'],
  ['Entities with a single source', SAMPLE.filter((e) => e.sources.length === 1).map((e) => e.id).join(', ') || 'none'],
  ['Entities whose sources are all from one work', SAMPLE.filter((e) => new Set(e.sources.map((s) => s[0])).size === 1).length],
  ['Biography claims with no source', claims.filter((c) => !c.src.length).length],
])
L.push('Distinct references by work:', '', ...Object.entries(works).sort((a, b) => b[1] - a[1]).map(([t, n]) => `- ${t}: ${n}`), '')
const vag = [...distinct].map((k) => k.split('§')).filter(([, r]) => vague.test(r))
L.push(`**Generic / non-specific locators (${vag.length})** — need a concrete chapter, volume or page:`, '', ...vag.map(([t, r]) => `- ${t} — "${r}"`), '')
L.push('**All other references are chapter-level** (book + chapter title, no volume / page / hadith number / edition). They stay visible in the app and are marked *incomplete*.', '')
const sourceless = new Map()
for (const e of SAMPLE) for (const [t] of e.sources) sourceless.set(t, (sourceless.get(t) ?? 0) + 1)
L.push('**Metadata still missing for every work:** edition / publisher, volume numbering, URL or digital reference. No quotation or passage is stored, so none is marked verified.', '')

// ---------- 6. relationships ----------
h(2, '6. Relationships')
const deg = new Map(SAMPLE.map((e) => [e.id, new Set(e.rel)]))
for (const e of SAMPLE) for (const r of e.rel) deg.get(r)?.add(e.id)
const asym = SAMPLE.flatMap((e) => e.rel.filter((r) => byId.has(r) && !byId.get(r).rel.includes(e.id)).map((r) => `${e.id}→${r}`))
const unknown = SAMPLE.flatMap((e) => e.rel.filter((r) => !byId.has(r)).map((r) => `${e.id}→${r}`))
const linked = (e) => [...deg.get(e.id)].map((i) => byId.get(i)).filter(Boolean)
const evNoPerson = SAMPLE.filter((e) => e.kind === 'event' && !linked(e).some((x) => x.kind === 'person' || x.kind === 'group'))
const evNoPlace = SAMPLE.filter((e) => e.kind === 'event' && !linked(e).some((x) => x.kind === 'place'))
const perNoEvent = SAMPLE.filter((e) => e.kind === 'person' && !linked(e).some((x) => x.kind === 'event'))
const plNoEvent = SAMPLE.filter((e) => e.kind === 'place' && !linked(e).some((x) => x.kind === 'event'))
const bioMissing = BIOS.flatMap((b) => { const ids = new Set(b.sections.flatMap((s) => [...(s.links ?? []), ...s.claims.flatMap((c) => c.links ?? [])])); return [...ids].filter((i) => i !== b.id && byId.has(i) && !deg.get(b.id).has(i)).map((i) => `${b.id}→${i}`) })
table(['Check', 'Result'], [
  ['Links to unknown ids', unknown.join(', ') || 'none'],
  ['One-directional links (A lists B, B does not list A)', `${asym.length} (the map and drawer read both directions, so they still display)`],
  ['Entities with ≤ 1 relationship', SAMPLE.filter((e) => deg.get(e.id).size <= 1).map((e) => e.id).join(', ') || 'none'],
  ['Timeline events with no linked companion', evNoPerson.map((e) => e.id).join(', ') || 'none'],
  ['Timeline events with no linked place', evNoPlace.map((e) => e.id).join(', ') || 'none'],
  ['People linked to no event', perNoEvent.map((e) => e.id).join(', ') || 'none'],
  ['Places linked to no event', plNoEvent.map((e) => e.id).join(', ') || 'none'],
  ['Biography links absent from the entity relations', bioMissing.join(', ') || 'none'],
])
L.push(`Biographies exist for ${BIOS.length} of ${SAMPLE.filter((e) => e.kind === 'person').length} people (${BIOS.map((b) => b.id).join(', ')}).`, '')

// ---------- 7. conflicting dates ----------
h(2, '7. Conflicting or inconsistent dates and accounts')
const ahToCe = (ah) => 622 + (ah - 1) * 0.9703
const dateIssues = []
for (const e of SAMPLE) {
  const ah = e.when.match(/(\d+)\s*هـ/), ce = e.when.match(/(\d{3})\s*(?:\/\s*\d{3})?\s*م/)
  if (!/^ت\./.test(e.when) && ah && ce && Math.abs(Number(ce[1]) - ahToCe(Number(ah[1]))) > 2) dateIssues.push(`${e.id}: "${e.when}" — AH ${ah[1]} ≈ ${Math.round(ahToCe(Number(ah[1])))} CE, text says ${ce[1]}`)
  const yrs = (e.when.match(/\d{3}/g) ?? []).map(Number), before = /^قبل/.test(e.when)
  if (yrs.length && !/^ت\./.test(e.when) && (before ? e.y > Math.max(...yrs) : e.y < Math.min(...yrs) - 3 || e.y > Math.max(...yrs) + 3)) dateIssues.push(`${e.id}: ordering year y=${e.y} is outside "${e.when}"`)
}
for (const b of BIOS) { const p = J(`src/bio/${b.id}/ar.json`); for (const j of b.journey) { const e = j.entity === j.id ? byId.get(j.id) : null; const ce = p.journey[j.id].when.match(/(\d{3})/g); if (e && ce && Math.abs(Number(ce[ce.length - 1]) - Math.floor(e.y)) > 2) dateIssues.push(`${b.id} milestone "${j.id}": "${p.journey[j.id].when}" vs entity year ${e.y}`) } }
L.push(dateIssues.length ? dateIssues.map((x) => `- ${x}`).join('\n') : '- No arithmetic AH/CE inconsistency and no ordering-year mismatch was found by the automatic checks.', '')
L.push('**Recorded disagreements between sources** (kept visible in the app, not resolved):', '')
const disp = SAMPLE.filter((e) => e.disputed)
L.push(...disp.map((e) => `- \`${e.id}\` — ${e.disputed}`), '')
L.push(`Bio claims classified disputed (${claims.filter((c) => c.certainty === 'disputed').length}): ${claims.filter((c) => c.certainty === 'disputed').map((c) => `${c.bio}:${c.id}`).join(', ')}.`, '')
L.push('Automatic checks cannot detect factual contradictions between prose passages; those need a historian.', '')

// ---------- 8. quotations ----------
h(2, '8. Quotations and verses embedded in prose (unverified)')
const quotes = SAMPLE.filter((e) => /[«﴿]/.test(e.summary + e.bio + e.context))
L.push('Entity texts containing a quotation mark («…») or Qur\'ān bracket (﴿…﴾). None has a verified passage record:', '', ...quotes.map((e) => `- \`${e.id}\``), '')

// ---------- 9. needs research ----------
h(2, '9. Content that needs additional research')
const research = [
  `All ${EVENTS.length} timeline events, ${SAMPLE.length} entities, ${BIOS.length} biographies and ${claims.length} claims need a historical review (nothing is reviewed).`,
  `${distinct.size} source references are incomplete (chapter-level); ${vag.length} are generic.`,
  `${EVENTS.filter((x) => x.certainty !== 'established').length} timeline events and ${claims.filter((c) => c.certainty !== 'established').length} biography claims are disputed or uncertain and need a source-by-source comparison.`,
  `${noClass.length} people / places / groups have no classification.`,
  `${quotes.length} entity texts contain quotations or verses whose exact wording has not been checked.`,
  `${SAMPLE.filter((e) => e.kind === 'person').length - BIOS.length} people have no biography; the relationship data between them is thin (see section 6).`,
  'Events not represented yet are tracked in the editorial backlog (`src/editorial/backlog.ts`, Backlog tab of the dashboard): Banū Qaynuqāʿ, Banū al-Naḍīr, Banū Qurayẓa and others — no details have been written.',
]
L.push(...research.map((x) => `- ${x}`), '')
writeFileSync('docs/CONTENT_AUDIT.md', L.join('\n') + '\n')
console.log(L.join('\n'))
