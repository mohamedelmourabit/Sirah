// Builds SQL that loads the bundled content into Supabase, so DB and app start identical.
// Translations are seeded as drafts and verification as PENDING_REVIEW exactly as bundled; reviewers promote rows later.
import { readFileSync, mkdtempSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { build } from 'esbuild'

const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`)
const j = (v) => `${q(JSON.stringify(v))}::jsonb`
const J = (l) => JSON.parse(readFileSync(new URL(`../src/locales/content/${l}.json`, import.meta.url), 'utf8'))

export async function loadSample() {
  const out = join(mkdtempSync(join(tmpdir(), 'sira-seed-')), 'data.mjs')
  await build({ entryPoints: ['src/data.ts'], bundle: true, format: 'esm', outfile: out, logLevel: 'silent' })
  return (await import(out)).SAMPLE
}

export async function buildSeed() {
  const sample = await loadSample()
  const sql = ['-- GENERATED by scripts/export-seed.mjs from src/data.ts + src/locales/content/*.json. Do not edit by hand.']
  for (const e of sample)
    sql.push(`insert into entities (id,kind,name,period,"when",y,summary,bio,context,sources,rel,disputed,kw) values (${[q(e.id), q(e.kind), q(e.name), q(e.period), q(e.when), e.y, q(e.summary), q(e.bio), q(e.context), j(e.sources), `array[${e.rel.map(q).join(',')}]::text[]`, q(e.disputed), q(e.kw)].join(',')}) on conflict (id) do nothing;`)
  for (const l of ['fr', 'en', 'es']) {
    const c = J(l)
    for (const e of sample) {
      const { translation, verification, ...fields } = c.entities[e.id]
      // sources: translate titles/refs exactly like localize() does
      const sources = e.sources.map(([t, r]) => [c.books[t] ?? t, c.refs[r] ?? r])
      sql.push(`insert into entity_translations (entity_id,lang,fields,translation_status,translation_reviewed_by,translation_reviewed_at) values (${[q(e.id), q(l), j({ ...fields, sources }), q(translation.status), q(translation.reviewed_by), q(translation.reviewed_at)].join(',')}) on conflict do nothing;`)
    }
  }
  for (const l of ['ar', 'fr', 'en', 'es']) {
    const c = J(l)
    for (const e of sample) {
      const v = c.entities[e.id].verification
      sql.push(`insert into entity_verification (entity_id,lang,status,reviewed_by,reviewed_at,note) values (${[q(e.id), q(l), q(v.status), q(v.reviewed_by), q(v.reviewed_at), q(v.note)].join(',')}) on conflict do nothing;`)
    }
  }
  return sql.join('\n') + '\n'
}
